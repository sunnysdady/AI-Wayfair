export function validateProductOperatingAudit(audit) {
  if (!audit || typeof audit !== "object") throw new Error("产品运营审计快照缺失");
  if (audit.asOfDate !== "2026-07-27") throw new Error("产品运营审计日期不匹配");
  if (!Array.isArray(audit.account) || audit.account.length < 2) throw new Error("账户利润对比缺失");
  if (!Array.isArray(audit.roles) || audit.roles.length !== 20) throw new Error("产品角色数量必须为 20");
  if (!audit.roleEvidenceThrough || !audit.costUpdatedAt || !audit.sourceSnapshotSha256) {
    throw new Error("审计版本、证据或成本时间戳缺失");
  }
  if (audit.review?.verdict !== "APPROVED_READ_ONLY") throw new Error("运营复核未批准只读展示");

  const listings = new Set(audit.roles.map((row) => row.listing));
  if (listings.size !== audit.roles.length) throw new Error("产品角色存在重复 Listing");

  const hardStops = audit.roles.filter((row) => row.actionGuardrail === "HARD_STOP_REQUIRED");
  if (hardStops.length !== 1 || hardStops[0].listing !== "DRCI1007") {
    throw new Error("只有 DRCI1007 可以提出 HARD_STOP_REQUIRED");
  }
  if (audit.roles.some((row) => row.tier.startsWith("G4") && row.actionGuardrail !== "HOLD")) {
    throw new Error("所有绩效型 G4 必须保持 HOLD");
  }
  if (audit.roles.some((row) => !row.operatorNote || !row.confidence || !Array.isArray(row.parts))) {
    throw new Error("产品角色必须包含运营说明、置信度和 Part 关联");
  }
  if (audit.roles.some((row) => row.platformStatus !== "NOT_VERIFIED" || row.lastExecutionResult !== null)) {
    throw new Error("只读审计不得伪造平台状态或执行结果");
  }
  return audit;
}

export function resolveProductOperatingRole(audit, listing) {
  const row = audit.roles.find((item) => item.listing === listing);
  if (row) return row;
  return {
    listing,
    tier: "UNCLASSIFIED",
    role: "未分级",
    confidence: "NONE",
    actionGuardrail: "HOLD",
    platformStatus: "NOT_VERIFIED",
    lastExecutionResult: null,
    parts: [],
    operatorNote: "没有版本化角色，保持只读并等待运营复核。",
  };
}
