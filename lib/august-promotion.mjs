export function promotionReviewSummary(plan = AUGUST_PROMOTION_PLAN) {
  const proposed = plan.filter((item) => item.action === "PROPOSE");
  const ziniaoReady = plan.filter((item) => item.canSubmitToZiniao);
  return {
    totalListings: plan.length,
    proposedListings: proposed.length,
    proposedParts: proposed.reduce((total, item) => total + item.parts.length, 0),
    heldOrExcludedListings: plan.length - proposed.length,
    pendingReviewListings: plan.filter((item) => item.reviewStatus === "PENDING_REVIEW").length,
    ziniaoReadyListings: ziniaoReady.length,
    submissionLocked: ziniaoReady.length === 0,
  };
}
